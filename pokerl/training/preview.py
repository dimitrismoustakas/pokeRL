"""Batched team preview inference for the live training policy."""

from __future__ import annotations

import time
from collections.abc import Sequence
from concurrent.futures import Future
from dataclasses import dataclass
from threading import Condition, Thread
from typing import Protocol

import numpy as np
import torch

from ..model.agent import PokeAgent
from .cuda_execution import cuda_model_execution


TeamPreviewTrainingSample = tuple[
    dict[str, np.ndarray],
    np.ndarray,
    float,
    np.ndarray,
]


@dataclass(frozen=True)
class TeamPreviewTrainingSelection:
    """Current-rollout preview samples selected for one optimizer step."""

    samples: tuple[TeamPreviewTrainingSample, ...]
    available_count: int
    used_count: int


@dataclass(frozen=True)
class VersionedTeamPreviewTrainingSample:
    """Trainer payload paired with the policy version that generated it."""

    sample: TeamPreviewTrainingSample
    policy_version: int


@dataclass(frozen=True)
class CurrentTeamPreviewTrainingData:
    """Current-policy samples after excluding update-boundary completions."""

    samples: tuple[TeamPreviewTrainingSample, ...]
    stale_excluded_count: int


@dataclass(frozen=True)
class TeamPreviewResult:
    """One preview decision and the policy version that produced it."""

    picks: np.ndarray
    policy_version: int | None


class _PreviewAndBattleTrainer(Protocol):
    def update_team_preview(
        self,
        data: list[TeamPreviewTrainingSample],
    ) -> dict[str, float]: ...

    def update(self, batch: object) -> dict[str, float]: ...


def filter_current_team_preview_training_samples(
    samples: Sequence[VersionedTeamPreviewTrainingSample],
    policy_version: int,
) -> CurrentTeamPreviewTrainingData:
    """Keep samples generated by this rollout's policy and count older ones."""
    if (
        isinstance(policy_version, bool)
        or not isinstance(policy_version, int)
        or policy_version < 0
    ):
        raise ValueError(f"policy_version must be non-negative (got {policy_version}).")

    current: list[TeamPreviewTrainingSample] = []
    stale_excluded_count = 0
    for versioned_sample in samples:
        if versioned_sample.policy_version > policy_version:
            raise ValueError(
                "Team-preview sample policy version cannot be newer than the "
                "current rollout policy version."
            )
        if versioned_sample.policy_version == policy_version:
            current.append(versioned_sample.sample)
        else:
            stale_excluded_count += 1
    return CurrentTeamPreviewTrainingData(
        samples=tuple(current),
        stale_excluded_count=stale_excluded_count,
    )


def select_team_preview_training_samples(
    samples: Sequence[TeamPreviewTrainingSample],
    max_samples: int,
    *,
    seed: int,
    update: int,
) -> TeamPreviewTrainingSelection:
    """Uniformly subsample one rollout's preview decisions without replacement.

    Deriving a fresh generator from the run seed and absolute update makes the
    selection reproducible after resume without persisting additional RNG state.
    Sorting the selected indices preserves rollout order without changing which
    subset is sampled.
    """
    if max_samples <= 0:
        raise ValueError(f"max_samples must be positive (got {max_samples}).")
    if not 0 <= seed < 2**32:
        raise ValueError(f"seed must be in [0, 2**32) (got {seed}).")
    if update < 0:
        raise ValueError(f"update must be non-negative (got {update}).")

    available_count = len(samples)
    if available_count <= max_samples:
        selected = tuple(samples)
    else:
        rng = np.random.default_rng(np.random.SeedSequence([seed, update]))
        selected_indices = np.sort(
            rng.choice(available_count, size=max_samples, replace=False)
        )
        selected = tuple(samples[int(index)] for index in selected_indices)

    return TeamPreviewTrainingSelection(
        samples=selected,
        available_count=available_count,
        used_count=len(selected),
    )


def update_preview_then_battle(
    trainer: _PreviewAndBattleTrainer,
    battle_batch: object,
    preview_samples: Sequence[TeamPreviewTrainingSample],
    max_preview_samples: int,
    *,
    seed: int,
    update: int,
) -> dict[str, float]:
    """Apply current-rollout preview learning before the battle PPO update."""
    selection = select_team_preview_training_samples(
        preview_samples,
        max_preview_samples,
        seed=seed,
        update=update,
    )
    metrics: dict[str, float] = {}
    if selection.samples:
        metrics.update(trainer.update_team_preview(list(selection.samples)))

    # Preview decisions were generated by the rollout policy. Update them
    # before PPO changes the shared agent so they are never trained stale.
    metrics.update(trainer.update(battle_batch))
    metrics["team_preview_samples_available_current"] = float(selection.available_count)
    metrics["team_preview_samples_used"] = float(selection.used_count)
    return metrics


@dataclass
class _PreviewRequest:
    obs: dict[str, np.ndarray]
    future: Future
    policy_version: int


class TeamPreviewBatcher:
    """Batches concurrent team preview requests from environment threads."""

    _COALESCE_WINDOW_SEC = 0.005
    _TARGET_BATCH_SIZE = 8
    _CLOSE_TIMEOUT_SEC = 60.0

    def __init__(
        self,
        agent: PokeAgent,
        device: torch.device,
        *,
        policy_version: int = 0,
    ):
        if (
            isinstance(policy_version, bool)
            or not isinstance(policy_version, int)
            or policy_version < 0
        ):
            raise ValueError(
                f"policy_version must be non-negative (got {policy_version})."
            )
        self._agent = agent
        self._device = device
        self._policy_version = policy_version
        self._pending: list[_PreviewRequest] = []
        self._active_request_count = 0
        self._closed = False
        self._fatal_error: BaseException | None = None
        self._condition = Condition()
        self._thread = Thread(
            target=self._run, name="team-preview-batcher", daemon=True
        )
        self._thread.start()

    @property
    def policy_version(self) -> int:
        with self._condition:
            return self._policy_version

    def advance_policy_version(self) -> int:
        """Advance after an optimizer cycle once old-version work is drained."""
        with self._condition:
            if self._closed:
                raise RuntimeError(
                    "Cannot advance the policy version of a closed preview batcher."
                )
            if self._pending or self._active_request_count:
                raise RuntimeError(
                    "Cannot advance team-preview policy version while inference "
                    "requests are pending or active."
                )
            self._policy_version += 1
            return self._policy_version

    def choose(self, obs: dict[str, np.ndarray]) -> TeamPreviewResult:
        return self.submit(obs).result()

    def submit(self, obs: dict[str, np.ndarray]) -> Future:
        future: Future = Future()
        with self._condition:
            if self._fatal_error is not None:
                raise RuntimeError(
                    "TeamPreviewBatcher worker failed."
                ) from self._fatal_error
            if self._closed:
                raise RuntimeError("TeamPreviewBatcher is closed.")
            if not self._thread.is_alive():
                raise RuntimeError("TeamPreviewBatcher worker stopped unexpectedly.")
            self._pending.append(
                _PreviewRequest(
                    obs=obs,
                    future=future,
                    policy_version=self._policy_version,
                )
            )
            self._condition.notify()
        return future

    def close(self) -> None:
        with self._condition:
            self._closed = True
            pending = list(self._pending)
            self._pending.clear()
            self._condition.notify_all()

        for request in pending:
            if not request.future.done():
                request.future.set_exception(RuntimeError("TeamPreviewBatcher closed."))

        if self._thread.is_alive():
            self._thread.join(timeout=self._CLOSE_TIMEOUT_SEC)
        if self._thread.is_alive():
            raise RuntimeError(
                "TeamPreviewBatcher worker did not stop within "
                f"{self._CLOSE_TIMEOUT_SEC:g} seconds."
            )

    def _run(self) -> None:
        try:
            self._run_loop()
        except BaseException as exc:
            with self._condition:
                self._fatal_error = exc
                self._closed = True
                pending = list(self._pending)
                self._pending.clear()
                self._condition.notify_all()
            for request in pending:
                if not request.future.done():
                    request.future.set_exception(
                        RuntimeError("TeamPreviewBatcher worker failed.")
                    )

    def _run_loop(self) -> None:
        while True:
            with self._condition:
                while not self._pending and not self._closed:
                    self._condition.wait()
                if self._closed and not self._pending:
                    return
                if self._COALESCE_WINDOW_SEC > 0:
                    deadline = time.perf_counter() + self._COALESCE_WINDOW_SEC
                    while (
                        not self._closed
                        and len(self._pending) < self._TARGET_BATCH_SIZE
                    ):
                        remaining = deadline - time.perf_counter()
                        if remaining <= 0:
                            break
                        self._condition.wait(timeout=remaining)
                batch = self._pending
                self._pending = []
                # Claim the snapshot before releasing the condition so version
                # advancement cannot slip between pending removal and inference.
                self._active_request_count = len(batch)

            batch = [
                request
                for request in batch
                if request.future.set_running_or_notify_cancel()
            ]
            if not batch:
                with self._condition:
                    self._active_request_count = 0
                    self._condition.notify_all()
                continue

            try:
                with cuda_model_execution(self._device):
                    if getattr(self._agent, "training", False):
                        raise RuntimeError(
                            "TeamPreviewBatcher cannot run while the live policy is in training mode."
                        )
                    obs_batch = {
                        key: torch.from_numpy(
                            np.stack([request.obs[key] for request in batch])
                        ).to(self._device)
                        for key in batch[0].obs
                    }
                    with torch.inference_mode():
                        picks = (
                            self._agent.team_preview(
                                obs_batch,
                                include_value=False,
                                include_policy_stats=False,
                                include_opponent_preview=False,
                            )["picks"]
                            .cpu()
                            .numpy()
                        )
            except Exception as exc:
                with self._condition:
                    self._active_request_count = 0
                    self._condition.notify_all()
                for request in batch:
                    if not request.future.done():
                        request.future.set_exception(exc)
            else:
                # Inference no longer reads model weights. Mark the batch idle
                # before publishing results so the optimizer may advance the
                # version without racing an old-version model invocation.
                with self._condition:
                    self._active_request_count = 0
                    self._condition.notify_all()
                for index, request in enumerate(batch):
                    if not request.future.done():
                        request.future.set_result(
                            TeamPreviewResult(
                                picks=picks[index],
                                policy_version=request.policy_version,
                            )
                        )
